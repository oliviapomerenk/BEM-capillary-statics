function dev = surfaceWavinessGUI()

% Used ChatGPT to develop this one too

    % Create figure
    fig = uifigure('Name', 'Surface Waviness', ...
                   'Position', [500 500 500 180], ...
                   'Resize', 'off');

    % Title
    uilabel(fig, ...
        'Position', [50 125 400 22], ...
        'Text', 'Select particle surface waviness:', ...
        'HorizontalAlignment', 'center');

    % Slider
    slider = uislider(fig, ...
        'Position', [80 90 340 3], ...
        'Limits', [0 10], ...
        'Value', 0, ...
        'MajorTicks', 0:1:10);

    % Left label
    uilabel(fig, ...
        'Position', [25 35 130 30], ...
        'Text', 'Flat (0%)', ...
        'HorizontalAlignment', 'left');

    % Right label
    uilabel(fig, ...
        'Position', [345 35 130 30], ...
        'Text', 'Very wavy (10%)', ...
        'HorizontalAlignment', 'right');

    % Current value
    valueLabel = uilabel(fig, ...
        'Position', [225 105 50 22], ...
        'Text', '0', ...
        'HorizontalAlignment', 'center');

    % Update displayed value
    slider.ValueChangedFcn = @sliderChanged;

    % OK button
    uibutton(fig, 'push', ...
        'Position', [215 15 70 25], ...
        'Text', 'OK', ...
        'ButtonPushedFcn', @submitCallback);

    % Wait for user input
    uiwait(fig);

    % Slider callback
    function sliderChanged(~, event)
        valueLabel.Text = sprintf('%.1f', event.Value);
    end

    % Submit callback
    function submitCallback(~, ~)
        dev = slider.Value / 100;

        uiresume(fig);
        delete(fig);
    end

end